/* Import edited artwork from the exports/ folder into the live map.  Namespace: Assets.ex
   Needs assets/exports-manifest.js (generated by tools/build-exports-manifest.js) loaded first.

   Assets.ex.place(name, x, y, opts) -> SVG markup string
     name   manifest key, e.g. '06-houses/school' (folder/file without extension)
     x, y   world position of the asset's ground anchor (the same point you would pass to the
            original JS asset, e.g. Assets.houses.school(x, y))
     opts.format  'svg' (default) or 'png'
     opts.scale   extra uniform scale around the anchor (default 1)
     opts.flip    true mirrors left/right around the anchor
   The file is drawn with <image>, so it works over file:// and keeps the edited file's own ids
   and styles isolated from the page. SMIL inside the file still plays; the page's CSS classes
   (spin, glow, ...) do not reach inside it. */
(function () {
  const A = window.Assets = window.Assets || {};
  const M = () => A.exportsManifest || {};
  const f = n => +(+n).toFixed(2);

  function has(name) { return !!M()[name]; }

  function place(name, x, y, opts = {}) {
    const e = M()[name];
    if (!e) return '';
    const [fx, fy, fw, fh] = e.frame;
    const href = A.url(opts.format === 'png' ? e.png : e.svg);
    const [sx, sy] = P(x, y, 0);
    const k = opts.scale || 1;
    const t = `translate(${f(sx)},${f(sy)})` + (k !== 1 || opts.flip ? ` scale(${opts.flip ? -k : k},${k})` : '');
    return `<g transform="${t}" class="ex ex-${name.replace(/[^a-z0-9]+/gi, '-')}"><image href="${href}" x="${fx}" y="${fy}" width="${fw}" height="${fh}" preserveAspectRatio="none"/></g>`;
  }

  // use the exported file if it exists, else fall back to the JS-drawn asset
  const pick = (name, x, y, fallback, opts) => has(name) ? place(name, x, y, opts) : fallback();

  A.ex = { place, has, pick, list: () => Object.keys(M()) };
})();
