/* Rebuild assets/exports-manifest.js from the SVGs in exports/svg.
   Usage (from the project root):  node tools/build-exports-manifest.js

   Each entry stores the asset's ORIGINAL frame: the viewBox it was exported with, in world-screen
   units, with (0,0) = the asset's ground anchor. Illustrator/Photoshop re-saves rewrite the viewBox
   to "0 0 W H", which loses that frame, so for any file whose viewBox now starts at 0 0 we keep the
   frame already stored in the manifest (or the FRAMES override below). */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..'), dir = path.join(root, 'exports', 'svg'), out = path.join(root, 'assets', 'exports-manifest.js');

// frames recovered by hand for files that were edited before the manifest existed
const FRAMES = {
  // (each export is the asset's bounding box at the origin, padded by 6 units on every side)
  '06-houses/school': [-32.2, -22.8, 78.5, 65.8],
  '04-trucks/petrotrade-tanker': [-27.75, -23.48, 54.63, 41.98],
  '04-trucks/petrotrade-tanker-oblique': [-27.85, -18.55, 55.15, 29.45],
  '05-cars/zetdc-truck-drum': [-25.65, -22.8, 51.49, 40.55]
};

let old = {};
try { const m = fs.readFileSync(out, 'utf8').match(/= (\{[\s\S]*\});/); if (m) old = JSON.parse(m[1]); } catch (e) { }

const list = {};
for (const folder of fs.readdirSync(dir).sort()) {
  const fdir = path.join(dir, folder);
  if (!fs.statSync(fdir).isDirectory()) continue;
  for (const file of fs.readdirSync(fdir).sort()) {
    if (!file.endsWith('.svg')) continue;
    const name = folder + '/' + file.slice(0, -4);
    const src = fs.readFileSync(path.join(fdir, file), 'utf8');
    const vb = (src.match(/viewBox="([^"]+)"/) || [])[1];
    const nums = vb ? vb.trim().split(/[\s,]+/).map(Number) : null;
    const edited = /Adobe Illustrator|Photoshop|inkscape|figma/i.test(src.slice(0, 600)) || (nums && nums[0] === 0 && nums[1] === 0);
    let frame = FRAMES[name] || (edited ? (old[name] && old[name].frame) : null) || (nums ? nums.map(v => +v.toFixed(2)) : null);
    if (!frame) { console.warn('skip (no frame):', name); continue; }
    list[name] = { svg: 'exports/svg/' + name + '.svg', png: 'exports/png/' + name + '.png', frame, edited: !!edited };
  }
}
fs.writeFileSync(out, '/* GENERATED by tools/build-exports-manifest.js - do not edit by hand. */\nwindow.Assets = window.Assets || {};\nwindow.Assets.exportsManifest = ' + JSON.stringify(list, null, 1) + ';\n');
console.log('wrote', Object.keys(list).length, 'entries;', 'edited:', Object.keys(list).filter(k => list[k].edited).join(', ') || 'none');
